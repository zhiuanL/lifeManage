import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { createElement } from "react";
import { MemoryRouter } from "react-router-dom";
import { afterEach, expect, it, vi } from "vitest";
import { createApplicationDependencies } from "../../src/app/applicationDependencies";
import { LifeOSProvider } from "../../src/app/LifeOSProvider";
import { VersionHistoryPage } from "../../src/pages/VersionHistoryPage";
import { GoalsPage } from "../../src/pages/GoalsPage";
vi.mock("../../src/app/applicationDependencies", () => ({ createApplicationDependencies: vi.fn() }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.resetAllMocks(); });
it("edits Chinese action feedback, preserves it on completion, and clears optional values", async () => {
  const actual = await vi.importActual<typeof import("../../src/app/applicationDependencies")>("../../src/app/applicationDependencies");
  const value = actual.createApplicationDependencies();
  await value.bootstrapApplicationService.bootstrap();
  vi.mocked(createApplicationDependencies).mockReturnValue(value);
  const action = await value.actionService.create({ title: "午间散步", notes: "", domainId: null, goalId: null, scheduledFor: null });
  render(createElement(LifeOSProvider, { children: createElement(MemoryRouter, { initialEntries: ["/goals?actionStatus=all"] }, createElement(GoalsPage)) }));
  fireEvent.click(await screen.findByRole("button", { name: "编辑行动：午间散步" }));
  let dialog = await screen.findByRole("dialog");
  expect([...dialog.querySelectorAll("details")].every(item => !item.open)).toBe(true);
  fireEvent.click(within(dialog).getByText("行动反馈（可选）"));
  fireEvent.change(within(dialog).getByLabelText("实际结果"), { target: { value: "走了两圈" } });
  fireEvent.change(within(dialog).getByLabelText("投入时间（分钟）"), { target: { value: "0" } });
  fireEvent.click(within(dialog).getByText("实施意图（可选）"));
  fireEvent.change(within(dialog).getByLabelText("触发情境"), { target: { value: "午饭后" } });
  vi.spyOn(value.actionService, "update").mockRejectedValueOnce(new Error("保存失败，请重试。"));
  fireEvent.click(within(dialog).getByRole("button", { name: "保存修改" }));
  expect(await within(dialog).findByRole("alert")).toHaveProperty("textContent", "保存失败，请重试。");
  expect(within(dialog).getByLabelText("实际结果")).toHaveProperty("value", "走了两圈");
  fireEvent.click(within(dialog).getByRole("button", { name: "保存修改" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  expect(await screen.findByText("0 分钟")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "标记为完成：午间散步" }));
  await screen.findByRole("button", { name: "恢复为未完成：午间散步" });
  expect((await value.actionService.list()).find(item => item.id === action.id)?.details).toMatchObject({ actualResult: "走了两圈", actualMinutes: 0, trigger: "午饭后" });
  fireEvent.click(screen.getByRole("button", { name: "编辑行动：午间散步" }));
  dialog = await screen.findByRole("dialog");
  fireEvent.click(within(dialog).getByText("行动反馈（可选）"));
  expect(within(dialog).getByLabelText("投入时间（分钟）")).toHaveProperty("value", "0");
  fireEvent.change(within(dialog).getByLabelText("投入时间（分钟）"), { target: { value: "" } });
  fireEvent.change(within(dialog).getByLabelText("实际结果"), { target: { value: "" } });
  fireEvent.click(within(dialog).getByRole("button", { name: "保存修改" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  expect((await value.actionService.list()).find(item => item.id === action.id)?.details).toMatchObject({ actualResult: "", actualMinutes: null, trigger: "午饭后" });
  expect(screen.queryByText("0 分钟")).toBeNull();
  expect(screen.getByRole("link", { name: "查看行动反馈历史：午间散步" }).getAttribute("href")).toBe(`/history?type=action&id=${encodeURIComponent(action.id)}`);
  cleanup();
  render(createElement(LifeOSProvider, { children: createElement(MemoryRouter, { initialEntries: [`/history?type=action&id=${action.id}`] }, createElement(VersionHistoryPage)) }));
  expect(await screen.findByText("行动反馈 · 午间散步")).toBeTruthy();
  const summaries = await screen.findAllByText("修改前版本");
  expect(summaries).toHaveLength(2);
  fireEvent.click(summaries[0]);
  expect(screen.getByText("走了两圈")).toBeTruthy();
  expect(screen.getByText("0 分钟")).toBeTruthy();
  expect(screen.getByText("已完成")).toBeTruthy();
  expect(screen.getByRole("link", { name: "返回原记录" }).getAttribute("href")).toBe(`/goals?actionStatus=all#action-${encodeURIComponent(action.id)}`);
  expect(screen.queryByRole("textbox")).toBeNull();
});
